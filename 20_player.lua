local need, todo = trainer.needs, trainer.todo
local m = trainer.section("Player", "Health, wanted level, movement and looks of the character you play.")

need(m:toggle("God mode", false, todo("Player > God mode"), "You take no damage from bullets, falls, fire or explosions."), "natives")
need(m:action("Heal", function() world.heal() end, "Fills your health."), "vitals")
need(m:toggle("Never wanted", false, todo("Player > Never wanted"), "The police never come after you, whatever you do."), "natives")
local wanted = need(m:number("Wanted level", 0, 1, todo("Player > Wanted level"), "Sets how many stars you have right now."), "natives")
wanted.min, wanted.max = 0, 5
need(m:toggle("Police ignore you", false, todo("Player > Police ignore you"), "Officers look past you even while you have stars."), "natives")
need(m:toggle("Invisible", false, todo("Player > Invisible"), "Other people cannot see your character."), "natives")
need(m:toggle("Noiseless", false, todo("Player > Noiseless"), "Your footsteps and actions make no sound."), "natives")
need(m:action("Clean up", todo("Player > Clean up"), "Washes blood, dirt and water off your character."), "natives")

local move = m:submenu("Movement", "Running, swimming, jumping and stamina.")
need(move:toggle("Fast run", false, todo("Player > Fast run"), "You run noticeably faster on foot."), "natives")
need(move:toggle("Fast swim", false, todo("Player > Fast swim"), "You swim noticeably faster."), "natives")
need(move:toggle("Super jump", false, todo("Player > Super jump"), "You jump several metres into the air."), "natives")
need(move:toggle("Unlimited stamina", false, todo("Player > Unlimited stamina"), "You never tire from running, swimming or cycling."), "natives")
need(move:toggle("No ragdoll", false, todo("Player > No ragdoll"), "You stay on your feet when you are hit or knocked over."), "natives")

local looks = m:submenu("Appearance", "Who you play and what they wear.")
need(looks:choice("Character", { "First", "Second" }, 1, todo("Player > Character"), "Switches to the other protagonist."), "natives")
need(looks:action("Random outfit", todo("Player > Random outfit"), "Dresses you in random clothes from the game's wardrobe."), "natives")
need(looks:action("Reset appearance", todo("Player > Reset appearance"), "Puts back your default clothes, hair and props."), "natives")

local anim = m:submenu("Animations", "Play an animation or scenario, or stop the current one.")
need(anim:action("Stop animation", todo("Player > Stop animation"), "Ends whatever animation or scenario you are playing."), "natives")
trainer.empty(anim, "No animations listed yet", "Animation names are added here as they are found in the game files.")
function trainer.add_animation(label, fn, desc)
  return trainer.fill(anim, need(anim:action(label, fn, desc), "calls"))
end

local info = m:submenu("Player info", "Live readings of your character.")
trainer.info(info, "Health", function()
  local p = trainer.find.player()
  return p and p.health and string.format("%.0f", p.health)
end, "Current health of your character.", "player")
trainer.info(info, "Armour", function()
  local e = world.player()
  local a = e and world.armour(e)
  return a and string.format("%.0f", a)
end, "Current armour of your character.", "player")
trainer.info(info, "Position", function()
  local p = trainer.find.player()
  return p and string.format("%.1f, %.1f, %.1f", p.x, p.y, p.z)
end, "Where you stand, in world coordinates.", "player")
trainer.info(info, "Heading", function()
  local p = trainer.find.player()
  return p and string.format("%.0f°", p.heading)
end, "The direction you face, in degrees.", "player")
